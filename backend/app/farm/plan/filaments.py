"""Filaments per printer model, taken from the OrcaSlicer and Bambu Studio profiles.

``filament_catalog.json`` is generated by ``scripts/farm_filament_catalog.py``, keyed by the slicers'
printer_model ("Creality K2 Pro"); the farm's printer-model table says which Printbuddy model that is.
"""

from __future__ import annotations

import json
from functools import cache
from pathlib import Path

from backend.app.farm.plates.printer_map import PrinterModelResolver, canonical_model

_FILE = Path(__file__).with_name("filament_catalog.json")


@cache
def catalog() -> dict[str, list[dict]]:
    return json.loads(_FILE.read_text(encoding="utf-8"))


def catalog_model(printer_model: str | None, resolver: PrinterModelResolver) -> str | None:
    """The catalog entry for a Printbuddy printer model ("P1S", "N7", "K2", "SV08")."""
    want = canonical_model(printer_model)
    if not want:
        return None
    for key in catalog():
        mapped = canonical_model(resolver.resolve(key).target_model)
        # Klipper printers unmapped in the table may be stored without the brand ("K1" for "Creality K1").
        if want in (mapped, canonical_model(key), canonical_model(key).split(" ", 1)[-1]):
            return key
    return None


def materials(printer_model: str | None, resolver: PrinterModelResolver) -> list[str]:
    """Filament types the slicer profiles offer for that printer model."""
    key = catalog_model(printer_model, resolver)
    return sorted({e["type"].upper() for e in catalog()[key] if e["type"]}) if key else []
