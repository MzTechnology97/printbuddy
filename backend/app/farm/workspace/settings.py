MAX_CHANGES = 2 * 1024 * 1024  # all the values of one save together
NIL = "nil"  # Orca/Bambu: "not set here, the preset's value applies"
MAX_TEXT = 256 * 1024  # one text or G-code value; the projects' longest are a few kB
_INT_RE = re.compile(r"^-?\d+$")
_FLOAT_RE = re.compile(r"^-?(\d+\.?\d*|\.\d+)([eE][-+]?\d+)?$")
_CONTROL_RE = re.compile(r"[\x00-\x08\x0b\x0c\x0e-\x1f\x7f]")


@cache
def options(slicer: str = "orcaslicer") -> dict[str, dict]:
    """The slicer's options by key (OrcaSlicer's for a slicer without its own data)."""
    name = slicer if slicer in SLICERS else "orcaslicer"
    return json.loads((DATA / f"{name}.json").read_text(encoding="utf-8"))["options"]


def _base(option: dict) -> str:
    """The slicer's type without ``co`` and the list ``s``: coFloatsOrPercents -> FloatOrPercent."""
    base = option["type"].removeprefix("co")
    return base[:-1] if option.get("vector") and base.endswith("s") else base


def kind(option: dict) -> str:
    """int, float, bool, enum, string or point."""
    base = _base(option).replace("sOrPercent", "OrPercent")
    if base == "Int":
        return "int"
    if base in ("Float", "Percent", "FloatOrPercent"):
        return "float"
    if base == "Bool":
        return "bool"
    if base == "Enum":
        return "enum"
    if base.startswith("Point"):
        return "point"
    return "string"


def percent(option: dict) -> str | None:
    """always (coPercent: ``15%``), either (coFloatOrPercent: ``0.4`` or ``90%``) or None."""
    base = _base(option).replace("sOrPercent", "OrPercent")
    return {"Percent": "always", "FloatOrPercent": "either"}.get(base)


def _elements(value) -> list | None:
    if isinstance(value, str):
        return [value]
    if isinstance(value, list) and all(isinstance(v, str) for v in value):
        return value
    return None


def _number(text: str, integer: bool) -> float | None:
    if integer:
        return int(text) if _INT_RE.match(text) else None
    if not _FLOAT_RE.match(text):
        return None
    number = float(text)
    return number if math.isfinite(number) else None


def _check(option: dict, text: str) -> str | None:
    """Why ``text`` is not a value of ``option`` (None: it is). ``nil`` is checked apart."""
    k = kind(option)
    if k == "bool":
        return None if text.lower() in ("0", "1", "true", "false") else "not a yes/no value"
    if k == "enum":
        if text in (option.get("enum") or []) or (option.get("open") and text and not _CONTROL_RE.search(text)):
            return None
        return "not one of the options"
    if k == "string":
        if len(text.encode("utf-8")) > MAX_TEXT:
            return f"longer than {MAX_TEXT // 1024} kB"
        if _CONTROL_RE.search(text) or (not option.get("multiline") and ("\n" in text or "\r" in text)):
            return "holds control characters"
        return None
    if k == "point":
        parts = text.split("x")
        ok = len(parts) in (2, 3) and all(_number(p.strip(), False) is not None for p in parts)
        return None if ok else "not a point (like 0x0)"
    # int, float, percentages
    if text.endswith("%") and percent(option) is None:
        return "this value is not a percentage"
    number = _number(text.removesuffix("%"), k == "int")
    if number is None:
        return "not a whole number" if k == "int" else "not a number"
    if option.get("min") is not None and number < option["min"]:
        return f"below the minimum {option['min']:g}"
    if option.get("max") is not None and number > option["max"]:
        return f"above the maximum {option['max']:g}"
    return None


def _reads_as(option: dict, value: str) -> bool:
    # a range check doesn't make a saved value unreadable: the slicer may allow more than its own GUI
    return value == NIL or _check({**option, "min": None, "max": None}, value) is None


def readonly_reason(key: str, option: dict | None, value) -> str | None:
    """Why a project value can't change (None: it can)."""
    if option is None:
        return "unknown"
    if key in IDENTITY:
        return "identity"
    if key in HARDWARE:
        return "hardware"
    if option.get("readonly"):
        return "slicer"
    if not option.get("section"):
        # not a process / filament / printer option: project data the slicer keeps itself (plate type,
        # flushing volumes, prime tower position, filament map) or a command-line / G-code placeholder key
        return "project"
    elements = _elements(value)
    if (
        elements is None
        # a list option may still hold one value (saved before the slicer made it per extruder): it reads
        or (isinstance(value, list) and not option.get("vector"))
        or not all(_reads_as(option, v) for v in elements)
        or (elements and all(v == NIL for v in elements))
    ):
        return "format"
    return None


def _system_sections(settings: dict) -> list[str] | None:
    """``different_settings_to_system``: keys that differ from the system preset, [process, filaments..., printer]."""
    diff = settings.get("different_settings_to_system")
    filaments = _elements(settings.get("filament_settings_id")) or []
    if not isinstance(diff, list) or len(diff) != len(filaments) + 2 or not all(isinstance(d, str) for d in diff):
        return None
    return diff


def _section_indexes(section: str, sections: list[str], elements: list[int] | None = None) -> list[int]:
    if section == "process":
        return [0]
    if section == "printer":
        return [len(sections) - 1]
    return [1 + i for i in (elements if elements is not None else range(len(sections) - 2))]


def describe(settings: dict, overrides: dict[str, list[dict]], slicer: str = "orcaslicer") -> list[dict]:
    """Every key of the project: the slicer's type info, project value, whether it can change, preset and
    object state.

    ``differs_from_system``: the project's value differs from the system preset it inherits (True), is
    the preset's (False), or the file doesn't say (None). The preset's own value is not in the file
    and is never guessed. ``overrides``: objects or parts that slice with their own value of the key.
    """
    known = options(slicer)
    sections = _system_sections(settings)
    out = []
    for key, value in settings.items():
        option = known.get(key)
        reason = readonly_reason(key, option, value)
        section = option.get("section") if option else None
        differs = None
        if sections is not None and section:
            differs = any(
                key in sections[i].split(";") for i in _section_indexes(section, sections) if i < len(sections)
            )
        out.append(
            {
                "key": key,
                "label": key,  # the browser shows the slicer's own label (orca-assets)
                "section": section,
                "type": kind(option) if option else "string",
                "percent": percent(option) if option else None,
                "nullable": bool(option and option.get("nullable")),
                "multiline": bool(option and option.get("multiline")),
                "min": option.get("min") if option else None,
                "max": option.get("max") if option else None,
                "options": [{"value": v, "label": v} for v in option["enum"]]
                if option and option.get("enum")
                else None,
                "open": bool(option and option.get("open")),
                "value": value,
                "editable": reason is None,
                "readonly_reason": reason,
                "differs_from_system": differs,
                "overrides": overrides.get(key, []),
            }
        )
    return out


class InvalidChange(ValueError):
    def __init__(self, errors: dict[str, str]):
        super().__init__("; ".join(f"{k}: {v}" for k, v in errors.items()))
        self.errors = errors


def _format_number(number: float) -> str:
    text = repr(number)
    if "e" in text or "E" in text:  # as the slicer's GUI writes it: 0.00001, not 1e-05
        text = f"{number:.15f}".rstrip("0").rstrip(".")
    return text[:-2] if text.endswith(".0") else text


def _normalize(option: dict, new, old: str) -> str:
    """``new`` (from the browser) in the format of ``old``; ValueError with the reason when it doesn't fit."""
    k = kind(option)
    if isinstance(new, bool):
        text = "1" if new else "0"
    elif k == "string":
        text = str(new).replace("\r\n", "\n")  # spaces and line breaks kept; the slicer writes \n
    else:
        text = str(new).strip()
    if text == old:
        return old
    if text == NIL:
        raise ValueError("the inherited value can't be set by hand")
    reason = _check(option, text)
    if reason is not None:
        raise ValueError(reason)
    if k == "bool":
        on = text.lower() in ("1", "true")
        return ("true" if on else "false") if old in ("true", "false") else ("1" if on else "0")
    if k in ("enum", "string"):
        return text
    if k == "point":
        return "x".join(_format_number(float(p.strip())) for p in text.split("x"))
    number_text = text.removesuffix("%")
    result = str(int(number_text)) if k == "int" else _format_number(float(number_text))
    # a percentage stays one; an mm-or-% value keeps the form typed
    return f"{result}%" if text.endswith("%") or percent(option) == "always" else result


def apply_changes(settings: dict, changes: dict, slicer: str = "orcaslicer") -> tuple[dict, list[dict]]:
    """``settings`` with ``changes`` applied (``InvalidChange`` lists every value refused).

    Returns the new settings and what actually changed: ``{key, before, after}``. A changed key is
    added to ``different_settings_to_system`` for its section, so the slicer shows it as a change
    against the system preset; nothing else is touched.
    """
    known = options(slicer)
    values = [v for value in changes.values() for v in (value if isinstance(value, list) else [value])]
    if sum(len(str(v).encode("utf-8")) for v in values) > MAX_CHANGES:
        raise InvalidChange({"changes": f"larger than {MAX_CHANGES // (1024 * 1024)} MB in total"})
    errors: dict[str, str] = {}
    result = dict(settings)
    applied = []
    sections = _system_sections(settings)
    sections = list(sections) if sections is not None else None
    for key, new in changes.items():
        old = settings.get(key)
        option = known.get(key)
        if old is None:
            errors[key] = "not in this project"
            continue
        reason = readonly_reason(key, option, old)
        if reason is not None:
            errors[key] = f"read only ({reason})"
            continue
        olds = _elements(old)
        news = new if isinstance(new, list) else [new]
        if isinstance(old, list) != isinstance(new, list) or len(news) != len(olds):
            errors[key] = f"expected {len(olds)} value(s)" if isinstance(old, list) else "expected one value"
            continue
        try:
            values = [_normalize(option, n, o) for n, o in zip(news, olds, strict=True)]
        except ValueError as exc:
            errors[key] = str(exc)
            continue
        value = values if isinstance(old, list) else values[0]
        if value == old:
            continue
        result[key] = value
        applied.append({"key": key, "before": old, "after": value})
        section = option.get("section")
        if sections is not None and section:
            changed = [i for i, (a, b) in enumerate(zip(olds, values, strict=True)) if a != b]
            for i in _section_indexes(section, sections, changed):
                if i >= len(sections) - 1 and section == "filament":
                    continue  # more values than filaments: the file doesn't say whose they are
                listed = [k for k in sections[i].split(";") if k]
                if key not in listed:
                    sections[i] = ";".join([*listed, key])
    if errors:
        raise InvalidChange(errors)
    if sections is not None and applied:
        result["different_settings_to_system"] = sections
    return result, applied


SETTINGS_ID = {"process": "print_settings_id", "filament": "filament_settings_id", "printer": "printer_settings_id"}
# what a printer preset switch must keep: the model and nozzle the copy's machine G-code, bed and farm queue go with
SAME_PRINTER = ("printer_model", "printer_variant", "nozzle_diameter")


def switch_refusal(target: dict, settings: dict) -> str | None:
    """Why ``target`` (a resolved preset, see ``presets.switch_target``) can't replace its section of the project.

    A process or filament preset must name the project's printer (or its system parent) in
    ``compatible_printers``; a printer preset must be for the same model and nozzle variant.
    """
    values = target["values"]
    if target["section"] == "printer":
        if any(_elements(values.get(k)) != _elements(settings.get(k)) for k in SAME_PRINTER):
            return "other_printer"
        return None
    printers = {settings.get("printer_settings_id"), *((_elements(settings.get("inherits_group")) or [""])[-1:])} - {""}
    listed = _elements(values.get("compatible_printers")) or []
    if listed:
        return None if printers & set(listed) else "incompatible"
    # shortcut: compatible_printers_condition isn't evaluated, so a preset that has only a condition isn't offered;
    # evaluate Orca's expression when generic presets are wanted
    if values.get("compatible_printers_condition"):
        return "condition"
    return None


def switch_preset(settings: dict, target: dict, slicer: str = "orcaslicer") -> tuple[dict, list[dict]]:
    """``settings`` with one section switched to ``target`` (OrcaSlicer's preset combo in the sidebar).

    Every key of the section the preset holds takes the preset's value (a filament's: that slot only), and the
    identity changes with it, together: ``*_settings_id``, the section's ``inherits_group`` and
    ``different_settings_to_system`` entries (the parent and the keys that differ from it, empty for a system
    preset), ``filament_ids`` and the compatibility lists, as PresetBundle::full_fff_config writes them. Refused
    whole (``InvalidChange``) rather than half applied: a preset whose values don't fit the project's layout (per
    extruder / per variant lists of another length), another printer model, an unreadable identity.
    """
    section, index = target["section"], int(target.get("index") or 0)
    sections = _system_sections(settings)
    if sections is None:
        raise InvalidChange({"different_settings_to_system": "unreadable: the switch can't be recorded"})
    if reason := switch_refusal(target, settings):
        raise InvalidChange({SETTINGS_ID[section]: f"not offered ({reason})"})
    variants = _elements(target["values"].get("filament_extruder_variant")) or []
    if section == "filament" and len(variants) > len(_elements(target["values"].get("filament_diameter")) or [""]):
        # shortcut: a multi-variant filament (one value per nozzle type) isn't resolved to the printer's variant here
        # (update_values_to_printer_extruders); do it when such presets are wanted
        raise InvalidChange({"filament_settings_id": "not offered (multi-variant filament)"})
    filaments = len(sections) - 2
    if section == "filament" and not 0 <= index < filaments:
        raise InvalidChange({"filament_settings_id": "no such filament"})
    slot = {"process": 0, "printer": len(sections) - 1}.get(section, 1 + index)
    known = options(slicer)
    result = dict(settings)
    put = result.__setitem__
    errors: dict[str, str] = {}

    # shortcut: a key no preset of the chain holds keeps the project's value, where OrcaSlicer would take its built-in
    # default (PrintConfig.cpp); the defaults aren't in slicer_options yet. Add them there to close the gap.
    for key, new in target["values"].items():
        option = known.get(key)
        if key in IDENTITY or not option or option.get("section") != section or key not in settings:
            continue
        old, news = settings[key], _elements(new)
        if section == "filament":
            # one value per filament, its preset's first (ConfigOptionVector::set in full_fff_config)
            if not isinstance(old, list) or len(old) != filaments or not news:
                errors[key] = "per-variant values: not switched here"
                continue
            put(key, [*old[:index], str(news[0]), *old[index + 1 :]])
        elif isinstance(old, list) != isinstance(new, list) or (isinstance(old, list) and len(old) != len(new)):
            errors[key] = "another per-extruder layout"
        else:
            put(key, [str(v) for v in new] if isinstance(new, list) else str(new))
    if errors:
        raise InvalidChange(errors)

    sid = SETTINGS_ID[section]
    if section == "filament":
        put(sid, [*settings[sid][:index], target["name"], *settings[sid][index + 1 :]])
        ids = settings.get("filament_ids")
        if isinstance(ids, list) and len(ids) == filaments and target.get("filament_id"):
            put("filament_ids", [*ids[:index], target["filament_id"], *ids[index + 1 :]])
    else:
        put(sid, target["name"])
    if section == "process" and "print_compatible_printers" in settings:
        put("print_compatible_printers", [str(v) for v in _elements(target["values"].get("compatible_printers")) or []])
    groups = settings.get("inherits_group")
    groups = list(groups) if isinstance(groups, list) else [""] * len(sections)  # left out when all are empty
    if len(groups) != len(sections):
        raise InvalidChange({"inherits_group": "unreadable: the switch can't be recorded"})
    groups[slot] = target.get("inherits") or ""
    if "inherits_group" in settings or any(groups):
        put("inherits_group", groups)
    diff = list(sections)
    differs = (
        k for k in target.get("differs") or [] if k not in IDENTITY and (known.get(k) or {}).get("section") == section
    )
    diff[slot] = ";".join(differs)
    put("different_settings_to_system", diff)
    # the conditions Orca keeps beside the names: [process, filaments...] for printers, [filaments...] for processes
    groups_at = {
        "compatible_machine_expression_group": ("compatible_printers_condition", None if section == "printer" else slot)
    }
    if section == "filament":
        groups_at["compatible_process_expression_group"] = ("compatible_prints_condition", index)
    for key, (condition, where) in groups_at.items():
        group = settings.get(key)
        if where is not None and isinstance(group, list) and where < len(group):
            put(key, [*group[:where], str(target["values"].get(condition) or ""), *group[where + 1 :]])
    applied = [{"key": k, "before": settings.get(k), "after": v} for k, v in result.items() if settings.get(k) != v]
    return result, applied
